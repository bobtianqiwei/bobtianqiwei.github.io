function renderImage(imageSrc, extraClass = "image-38") {
  return `<img src="${imageSrc}" loading="lazy" alt="" class="${extraClass}">`;
}

function renderCardGrid(cards) {
  const columns = [cards.slice(0, 1), cards.slice(1, 2), cards.slice(2, 3)];
  return `    <div class="work-columns w-row">
      <div class="column-13 w-col w-col-4">
${columns[0].map((card) => renderCard(card)).join("\n")}
      </div>
      <div class="column-14 w-col w-col-4">
${columns[1].map((card) => renderCard(card)).join("\n")}
      </div>
      <div class="column-15 w-col w-col-4">
${columns[2].map((card) => renderCard(card)).join("\n")}
      </div>
    </div>`;
}

function renderCard(card) {
  return `        <a href="${card.href}" target="_blank" class="project-link-block w-inline-block">
          <div class="w-container">${renderImage(card.image)}
            <div class="work-page-project-name">${card.title}</div>
          </div>
        </a>`;
}

function renderYouTube(video) {
  return `    <div style="padding-top:56.17021276595745%" class="w-embed-youtubevideo"><iframe src="https://www.youtube.com/embed/${video.youtubeId}?rel=0&amp;controls=1&amp;autoplay=0&amp;mute=0&amp;start=0" frameborder="0" style="position:absolute;left:0;top:0;width:100%;height:100%;pointer-events:auto" allow="autoplay; encrypted-media" allowfullscreen="" title="${video.title}"></iframe></div>
    <p class="image-description">${video.caption}</p>`;
}

function renderSharedSections(project) {
  const overview = project.content.sections.overview;
  const primary = project.content.sections.primary;
  const primaryBlocks = (primary.blocks || []).map((block) => {
    const cards = block.cardGroup ? project.content.cardGroups[block.cardGroup] || [] : [];
    return `    <p class="big-title-3">${block.title}</p>
    <div class="paragraph-light">${block.bodyHtml}</div>
${cards.length ? `${renderCardGrid(cards)}\n` : ""}`;
  }).join("");

  const extraVideo = overview.extraVideo ? `${renderYouTube(overview.extraVideo)}\n` : "";
  return `${renderYouTube(project.content.hero.video)}
    <div class="big-title-2">${overview.title}</div>
    <div class="paragraph-light">${overview.bodyHtml}</div>
${extraVideo}    <div class="big-title-2">${primary.title}</div>
${primaryBlocks}`;
}

