function getSectionBodyHtml(section) {
  return section.bodyHtml || section.html || "";
}

function getSectionCards(project, section) {
  if (Array.isArray(section.cards)) {
    return section.cards;
  }

  if (section.cardGroup) {
    return getCardGroup(project, section.cardGroup);
  }

  return [];
}

function getSectionVideos(section) {
  const videos = [];

  if (section.video) {
    videos.push(section.video);
  }

  if (section.extraVideo) {
    videos.push(section.extraVideo);
  }

  if (Array.isArray(section.videos)) {
    videos.push(...section.videos);
  }

  return videos.map((video, index) =>
    typeof video === "string"
      ? {
          src: video,
          title: `Project video ${index + 1}`,
          caption: ""
        }
      : video
  );
}

function getSectionFigures(section) {
  const figures = [];

  if (section.figure) {
    figures.push(section.figure);
  }

  if (Array.isArray(section.figures)) {
    figures.push(...section.figures);
  }

  return figures.map((figure) =>
    typeof figure === "string"
      ? { src: figure }
      : figure
  );
}

function normalizeSections(project) {
  if (Array.isArray(project.content.sections)) {
    return project.content.sections;
  }

  const overview = project.content.sections?.overview;
  const primary = project.content.sections?.primary;
  const sections = [];

  if (overview) {
    sections.push({
      title: overview.title,
      bodyHtml: overview.bodyHtml,
      video: overview.extraVideo
    });
  }

  if (primary) {
    sections.push({
      title: primary.title,
      blocks: primary.blocks || []
    });
  }

  return sections;
}

