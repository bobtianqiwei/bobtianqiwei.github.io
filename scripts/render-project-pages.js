function renderProjectView(project, view) {
  const resolvedLayout = view.layout === "portfolio-case-study" && view.outputPath.startsWith("design/")
    ? "design-case-study"
    : view.layout === "portfolio-case-study"
      ? "swe-classic-case-study"
      : view.layout;
  let rendered;

  if (resolvedLayout === "design-case-study") {
    rendered = renderDesignCaseStudy(project, view);
  } else if (resolvedLayout === "plain-text-page") {
    rendered = renderPlainTextPage(project);
  } else if (resolvedLayout === "swe-classic-case-study") {
    rendered = renderSweClassicCaseStudy(project, view);
  } else if (resolvedLayout === "portfolio-case-study") {
    rendered = {
      body: renderPortfolioCaseStudy(project, view),
      extraHead: ""
    };
  } else {
    rendered = renderWorksCaseStudy(project, view);
  }

  const shell = resolvedLayout === "swe-classic-case-study"
    ? classicPageShell
    : resolvedLayout === "plain-text-page"
      ? plainTextPageShell
      : pageShell;

  return shell({
    title: view.metaTitle || project.content.title,
    description: project.content.description,
    body: rendered.body,
    extraHead: rendered.extraHead,
    appearance: view.appearance || ""
  });
}

function main() {
  const projects = loadProjects();
  for (const project of projects) {
    for (const view of Object.values(project.views || {})) {
      writeFile(view.outputPath, renderProjectView(project, view));
    }

    for (const childPage of project.childPages || []) {
      const childProject = createRenderableProject(project, childPage);
      for (const view of Object.values(childPage.views || {})) {
        writeFile(view.outputPath, renderProjectView(childProject, view));
      }
    }
  }
}

main();
