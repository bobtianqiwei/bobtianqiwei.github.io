function renderSharedSections(project) {
  const overview = project.content.sections.overview;
  const primary = project.content.sections.primary;
  const primaryBlocks = (primary.blocks || []).map((block) => {
    const cards = block.cardGroup ? project.content.cardGroups[block.cardGroup] || [] : [];
    return `    <p class="big-title-3">${block.title}</p>
    <div class="paragraph-light">${block.bodyHtml}</div>
${cards.length ? `${renderCardGrid(cards)}\n` : ""}`;
  }).join("");

  const extraVideo = overview.extraVideo ? `${renderYouTube(overview.extraVideo)}\n` : "";
  return `${renderYouTube(project.content.hero.video)}
    <div class="big-title-2">${overview.title}</div>
    <div class="paragraph-light">${overview.bodyHtml}</div>
${extraVideo}    <div class="big-title-2">${primary.title}</div>
${primaryBlocks}`;
}

