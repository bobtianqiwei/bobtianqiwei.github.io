function renderProjectView(project, view) {
  const body = view.layout === "portfolio-case-study"
    ? renderPortfolioCaseStudy(project, view)
    : renderWorksCaseStudy(project, view);

  return pageShell({
    title: view.metaTitle || project.content.title,
    description: project.content.description,
    body
  });
}

function main() {
  const projects = loadProjects();
  for (const project of projects) {
    for (const view of Object.values(project.views || {})) {
      writeFile(view.outputPath, renderProjectView(project, view));
    }
  }
}

main();
