function remapSweClassicHref(href) {
  if (typeof href !== "string") {
    return href;
  }

  // Keep shared content canonical, but rewrite internal work links when
  // generating SWE classic pages so new project pages point to classic siblings.
  return href.replace(/^\/works\/([^/]+)\/?$/, "/swe/classic/$1/");
}

function remapSweClassicHtml(html) {
  if (typeof html !== "string") {
    return html;
  }

  return html.replace(/href="\/works\/([^"/]+)\/?"/g, 'href="/swe/classic/$1/"');
}

